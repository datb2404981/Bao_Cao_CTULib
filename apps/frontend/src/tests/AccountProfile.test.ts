import { beforeEach, expect, it, vi } from 'vitest'
import { flushPromises, mount } from '@vue/test-utils'
import AccountProfile from '../components/profile/AccountProfile.vue'
import { request } from '../services/request'
vi.mock('../services/request', () => ({ request: vi.fn() }))
vi.mock('../services/auth', () => ({ refreshAuthorization: vi.fn() }))
const profile = { ctuIdentifier: 'B2404981', email: 'old@example.com', role: 'READER', hasProfile: true, fullName: 'Nguyễn An', phoneNumber: '', address: '', dateOfBirth: '', readerType: 'STUDENT', facultyName: 'CNTT', position: '' }
beforeEach(() => { vi.resetAllMocks(); vi.mocked(request).mockResolvedValue(profile) })
it('hiển thị hồ sơ và lưu thông tin cá nhân qua API của chính người dùng', async () => {
  vi.mocked(request).mockResolvedValueOnce(profile).mockResolvedValueOnce({ ...profile, fullName: 'Nguyễn Bình' })
  const view = mount(AccountProfile, { props: { busy: false, signOutError: '' } })
  await flushPromises()
  expect(view.text()).toContain('CNTT')
  expect(view.text()).not.toContain('Chỉnh sửa')
  await view.get('button[aria-label^="Sửa họ và tên"]').trigger('click')
  await view.get('input[autocomplete=name]').setValue('Nguyễn Bình')
  await view.get('input[autocomplete=name]').trigger('keydown.enter')
  await flushPromises()
  expect(request).toHaveBeenCalledWith('/api/v1/auth/profile/personal', 'PATCH', { fullName: 'Nguyễn Bình', phoneNumber: '', address: '' })
  expect(view.get('button[aria-label^="Sửa họ và tên"]').text()).toBe('Nguyễn Bình')
  expect(view.text()).toContain('Thông tin đã được cập nhật')
})
it('giữ email đang sửa khi API từ chối và cho phép thử lại', async () => {
  vi.mocked(request).mockResolvedValueOnce(profile).mockRejectedValueOnce(new Error('Email đã được sử dụng'))
  const view = mount(AccountProfile, { props: { busy: false, signOutError: '' } })
  await flushPromises()
  await view.get('button[aria-label^="Sửa địa chỉ email"]').trigger('click')
  await view.get('input[type=email]').setValue('new@example.com')
  await view.get('input[type=email]').trigger('blur')
  await flushPromises()
  expect(view.get('[role=alert]').text()).toContain('Email đã được sử dụng')
  expect((view.get('input[type=email]').element as HTMLInputElement).value).toBe('new@example.com')
  expect(view.get('input[type=email]').attributes('aria-invalid')).toBe('true')
})
it('tự lưu khi rời ô và hủy bằng Esc mà không gọi API', async () => {
  vi.mocked(request).mockResolvedValueOnce(profile).mockResolvedValueOnce({ ...profile, phoneNumber: '0912345678' })
  const view = mount(AccountProfile, { props: { busy: false, signOutError: '' } })
  await flushPromises()
  await view.get('button[aria-label^="Sửa số điện thoại"]').trigger('click')
  await view.get('input[type=tel]').setValue('0912345678')
  await view.get('input[type=tel]').trigger('blur')
  await flushPromises()
  expect(request).toHaveBeenCalledWith('/api/v1/auth/profile/personal', 'PATCH', { fullName: 'Nguyễn An', phoneNumber: '0912345678', address: '' })
  await view.get('button[aria-label^="Sửa địa chỉ"]').trigger('click')
  await view.get('input[autocomplete=street-address]').setValue('Cần Thơ')
  await view.get('input[autocomplete=street-address]').trigger('keydown.esc')
  expect(view.find('input[autocomplete=street-address]').exists()).toBe(false)
  expect(vi.mocked(request).mock.calls).toHaveLength(2)
})
it('giải thích khi hồ sơ cá nhân chưa tồn tại', async () => {
  vi.mocked(request).mockResolvedValue({ ...profile, hasProfile: false })
  const view = mount(AccountProfile, { props: { busy: false, signOutError: '' } })
  await flushPromises()
  expect(view.text()).toContain('Hồ sơ cá nhân chưa được tạo')
  expect(view.findAll('button').some(button => button.text() === 'Chỉnh sửa')).toBe(false)
})
